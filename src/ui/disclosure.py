from __future__ import annotations

#: 这个系统**不具备**的能力。逐条列出来，而不是用「功能有限」带过。
NOT_PROVIDED: tuple[str, ...] = (
    "没有会话过期机制：登录状态一直有效，直到你登出或关闭页面",
    "没有登录限流：连续尝试密码不会被拦住",
    "没有找回密码：忘了密码只能由管理员重置",
    "没有 CSRF 防护",
    "刷新浏览器页面后需要重新登录——凭据只存在会话状态里，"
    "不写 Cookie、不放进网址，所以也没法被复制分享出去",
)


def boundary_summary() -> str:
    """一句话定性。**不要把它改写成「安全的用户系统」之类的话。**"""
    return "本系统的账号体系是**演示级鉴权**，用于展示角色与数据隔离，不是生产级方案。"


def boundary_lines() -> list[str]:
    """完整清单：先定性，再逐条列出不具备的能力。"""
    return [boundary_summary(), *NOT_PROVIDED]


